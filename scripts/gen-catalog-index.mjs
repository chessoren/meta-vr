// Regenerates src/core/catalog-data.generated.ts from the real model specs (src/lib3d/models/*),
// merging in any extra tags / sound-alikes already present in the current index.
// Run: node scripts/gen-catalog-index.mjs   (a unit test fails if the two drift apart)
import { build } from 'esbuild';
import { writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const dir = mkdtempSync(join(tmpdir(), 'loci-cat-'));
const bundle = async (entry, name) => {
  const outfile = join(dir, name);
  await build({ entryPoints: [entry], bundle: true, platform: 'node', format: 'esm', outfile, logLevel: 'error' });
  return import(pathToFileURL(outfile).href);
};
const { CATALOG } = await bundle('src/lib3d/catalog.ts', 'catalog.mjs');
let previous = [];
try {
  previous = (await bundle('src/core/catalog-index.ts', 'index.mjs')).CATALOG_INDEX;
} catch {}
const prev = new Map(previous.map((e) => [e.id, e]));
const clean = (s) => String(s).normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z0-9 '-]/g, ' ').replace(/\s+/g, ' ').trim();
const uniq = (a) => [...new Set(a.map(clean).filter(Boolean))];
const data = CATALOG.map((s) => {
  const p = prev.get(s.id);
  const entry = {
    id: s.id,
    name: s.name,
    category: s.category,
    tags: uniq([...(p?.tags ?? []), ...s.tags]).slice(0, 28),
    soundsLike: uniq([...(p?.soundsLike ?? []), ...s.soundsLike]).slice(0, 18),
    anims: [...s.anims],
  };
  if (s.text) entry.text = true;
  return entry;
});
const body = `/* eslint-disable */
// GENERATED by scripts/gen-catalog-index.mjs from src/lib3d/models/* — do not edit by hand.
import type { CatalogEntry } from './catalog-index';

export const CATALOG_DATA: CatalogEntry[] = ${JSON.stringify(data, null, 1)};
`;
writeFileSync('src/core/catalog-data.generated.ts', body);
console.log(`✓ ${data.length} catalog entries written`);
